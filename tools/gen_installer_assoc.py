"""Write installer/assoc.iss: the "Open with" + Default-apps registry entries for every supported extension.

Keeps the installer in sync with egplayer.paths.VIDEO_EXTS / AUDIO_EXTS. Entries are only added to
"Open with" (OpenWithProgids) — EG Player never takes over existing default apps.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from egplayer.paths import AUDIO_EXTS, VIDEO_EXTS  # noqa: E402

PROG = "EGPlayer.Media"
EXE = r"{app}\EGPlayer.exe"
CMD = f'""{EXE}"" ""%1""'
T = "Tasks: openwith"
lines = [
    "; generated by tools/gen_installer_assoc.py — do not edit",
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}"; ValueType: string; ValueName: ""; '
    f'ValueData: "EG Player media file"; Flags: uninsdeletekey; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}"; ValueType: string; ValueName: "FriendlyTypeName"; '
    f'ValueData: "EG Player media file"; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}\\DefaultIcon"; ValueType: string; ValueName: ""; '
    f'ValueData: "{EXE},0"; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}\\shell"; ValueType: string; ValueName: ""; ValueData: "open"; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}\\shell\\open"; ValueType: string; ValueName: ""; '
    f'ValueData: "Play with EG Player"; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\{PROG}\\shell\\open\\command"; ValueType: string; ValueName: ""; '
    f'ValueData: "{CMD}"; {T}',
    # the exe itself, so it shows in "Choose another app" with a proper name and icon
    f'Root: HKA; Subkey: "Software\\Classes\\Applications\\EGPlayer.exe"; ValueType: string; '
    f'ValueName: "FriendlyAppName"; ValueData: "EG Player"; Flags: uninsdeletekey; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\Applications\\EGPlayer.exe\\DefaultIcon"; ValueType: string; '
    f'ValueName: ""; ValueData: "{EXE},0"; {T}',
    f'Root: HKA; Subkey: "Software\\Classes\\Applications\\EGPlayer.exe\\shell\\open\\command"; '
    f'ValueType: string; ValueName: ""; ValueData: "{CMD}"; {T}',
    # Settings > Apps > Default apps
    f'Root: HKA; Subkey: "Software\\EGPlayer\\Capabilities"; ValueType: string; ValueName: "ApplicationName"; '
    f'ValueData: "EG Player"; Flags: uninsdeletekey; {T}',
    f'Root: HKA; Subkey: "Software\\EGPlayer\\Capabilities"; ValueType: string; '
    f'ValueName: "ApplicationDescription"; ValueData: "Fast video player with frame-accurate scrubbing '
    f'and a mini editor"; {T}',
    f'Root: HKA; Subkey: "Software\\EGPlayer\\Capabilities"; ValueType: string; ValueName: "ApplicationIcon"; '
    f'ValueData: "{EXE},0"; {T}',
    f'Root: HKA; Subkey: "Software\\RegisteredApplications"; ValueType: string; ValueName: "EG Player"; '
    f'ValueData: "Software\\EGPlayer\\Capabilities"; Flags: uninsdeletevalue; {T}',
]
for ext in sorted(VIDEO_EXTS | AUDIO_EXTS):
    lines.append(f'Root: HKA; Subkey: "Software\\Classes\\.{ext}\\OpenWithProgids"; ValueType: string; '
                 f'ValueName: "{PROG}"; ValueData: ""; Flags: uninsdeletevalue; {T}')
    lines.append(f'Root: HKA; Subkey: "Software\\Classes\\Applications\\EGPlayer.exe\\SupportedTypes"; '
                 f'ValueType: string; ValueName: ".{ext}"; ValueData: ""; {T}')
    lines.append(f'Root: HKA; Subkey: "Software\\EGPlayer\\Capabilities\\FileAssociations"; ValueType: string; '
                 f'ValueName: ".{ext}"; ValueData: "{PROG}"; {T}')

out = os.path.join(ROOT, "installer", "assoc.iss")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {out} ({len(VIDEO_EXTS | AUDIO_EXTS)} extensions)")
